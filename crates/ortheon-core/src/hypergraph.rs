use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet, VecDeque};

/// Stable identifier for a hyperedge.
pub type HyperedgeId = u64;

/// Errors returned by hypergraph construction and validation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HypergraphError {
    /// A vertex identifier already exists.
    DuplicateNode(u64),
    /// A hyperedge identifier already exists.
    DuplicateHyperedge(u64),
    /// A hyperedge must contain at least one vertex.
    EmptyHyperedge,
    /// A hyperedge references a vertex outside the model.
    MissingNode(u64),
    /// The stored model violates an invariant.
    InvalidRepresentation(String),
}

impl std::fmt::Display for HypergraphError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::DuplicateNode(id) => write!(f, "node {id} already exists"),
            Self::DuplicateHyperedge(id) => write!(f, "hyperedge {id} already exists"),
            Self::EmptyHyperedge => write!(f, "hyperedges must contain at least one node"),
            Self::MissingNode(id) => write!(f, "hyperedge references missing node {id}"),
            Self::InvalidRepresentation(message) => write!(f, "invalid hypergraph: {message}"),
        }
    }
}

impl std::error::Error for HypergraphError {}

/// A finite labeled hypergraph.
///
/// A hyperedge is a non-empty set of vertices and may connect more than two
/// vertices. Hyperedge identifiers are stable; parallel identical member
/// sets are allowed when they have different identifiers.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Hypergraph {
    nodes: BTreeMap<u64, String>,
    edges: BTreeMap<HyperedgeId, BTreeSet<u64>>,
}

impl Hypergraph {
    /// Create an empty hypergraph.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Number of vertices.
    #[must_use]
    pub fn node_count(&self) -> usize {
        self.nodes.len()
    }

    /// Number of hyperedges.
    #[must_use]
    pub fn hyperedge_count(&self) -> usize {
        self.edges.len()
    }

    /// Number of vertex-hyperedge incidences.
    #[must_use]
    pub fn incidence_count(&self) -> usize {
        self.edges.values().map(BTreeSet::len).sum()
    }

    /// Iterate over vertices in identifier order.
    pub fn nodes(&self) -> impl Iterator<Item = (u64, &str)> {
        self.nodes.iter().map(|(id, label)| (*id, label.as_str()))
    }

    /// Iterate over hyperedges and their ordered members.
    pub fn hyperedges(&self) -> impl Iterator<Item = (HyperedgeId, &BTreeSet<u64>)> {
        self.edges.iter().map(|(id, members)| (*id, members))
    }

    /// Insert a labeled vertex.
    pub fn add_node(&mut self, id: u64, label: impl Into<String>) -> Result<(), HypergraphError> {
        if self.nodes.contains_key(&id) {
            return Err(HypergraphError::DuplicateNode(id));
        }
        self.nodes.insert(id, label.into());
        Ok(())
    }

    /// Insert a non-empty hyperedge after validating all member vertices.
    pub fn add_hyperedge(
        &mut self,
        id: HyperedgeId,
        members: impl IntoIterator<Item = u64>,
    ) -> Result<(), HypergraphError> {
        if self.edges.contains_key(&id) {
            return Err(HypergraphError::DuplicateHyperedge(id));
        }
        let members: BTreeSet<u64> = members.into_iter().collect();
        if members.is_empty() {
            return Err(HypergraphError::EmptyHyperedge);
        }
        for node in &members {
            if !self.nodes.contains_key(node) {
                return Err(HypergraphError::MissingNode(*node));
            }
        }
        self.edges.insert(id, members);
        Ok(())
    }

    /// Return the number of hyperedges incident to a vertex.
    pub fn degree(&self, node: u64) -> Option<usize> {
        self.nodes.contains_key(&node).then(|| {
            self.edges.values().filter(|members| members.contains(&node)).count()
        })
    }

    /// Validate the finite incidence structure.
    pub fn validate(&self) -> Result<(), HypergraphError> {
        for (edge_id, members) in &self.edges {
            if members.is_empty() {
                return Err(HypergraphError::InvalidRepresentation(
                    format!("hyperedge {edge_id} is empty"),
                ));
            }
            for node in members {
                if !self.nodes.contains_key(node) {
                    return Err(HypergraphError::InvalidRepresentation(
                        format!("hyperedge {edge_id} references absent node {node}"),
                    ));
                }
            }
        }
        Ok(())
    }

    /// Compute connected components under the relation generated by shared hyperedges.
    ///
    /// Isolated vertices are retained as singleton components. Each hyperedge
    /// is expanded only once during traversal.
    pub fn connected_components(&self) -> Result<Vec<Vec<u64>>, HypergraphError> {
        self.validate()?;
        let mut incidence: BTreeMap<u64, Vec<HyperedgeId>> =
            self.nodes.keys().map(|id| (*id, Vec::new())).collect();
        for (edge_id, members) in &self.edges {
            for node in members {
                incidence.get_mut(node).expect("validated node").push(*edge_id);
            }
        }

        let mut unseen: BTreeSet<u64> = self.nodes.keys().copied().collect();
        let mut visited_edges = BTreeSet::new();
        let mut result = Vec::new();

        while let Some(start) = unseen.pop_first() {
            let mut component = BTreeSet::from([start]);
            let mut queue = VecDeque::from([start]);
            while let Some(current) = queue.pop_front() {
                for edge_id in incidence.get(&current).into_iter().flatten() {
                    if visited_edges.insert(*edge_id) {
                        for member in self.edges.get(edge_id).expect("indexed hyperedge") {
                            if unseen.remove(member) {
                                component.insert(*member);
                                queue.push_back(*member);
                            }
                        }
                    }
                }
            }
            result.push(component.into_iter().collect());
        }
        Ok(result)
    }

    /// Return a versioned SHA-256 fingerprint of the canonical labeled incidence model.
    ///
    /// Vertex and hyperedge identifiers are significant. This is not an
    /// isomorphism-invariant hypergraph hash.
    #[must_use]
    pub fn fingerprint(&self) -> String {
        let mut hasher = Sha256::new();
        hasher.update(b"ORTHEON-HYPERGRAPH\0");
        hasher.update(1_u16.to_be_bytes());
        hasher.update((self.nodes.len() as u64).to_be_bytes());
        for (id, label) in &self.nodes {
            hasher.update(id.to_be_bytes());
            hasher.update((label.len() as u64).to_be_bytes());
            hasher.update(label.as_bytes());
        }
        hasher.update((self.edges.len() as u64).to_be_bytes());
        for (edge_id, members) in &self.edges {
            hasher.update(edge_id.to_be_bytes());
            hasher.update((members.len() as u64).to_be_bytes());
            for member in members {
                hasher.update(member.to_be_bytes());
            }
        }
        format!("{:x}", hasher.finalize())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn n_ary_hyperedge_connects_all_members() {
        let mut graph = Hypergraph::new();
        for id in 1..=4 {
            graph.add_node(id, id.to_string()).unwrap();
        }
        graph.add_hyperedge(10, [1, 2, 3]).unwrap();
        assert_eq!(graph.connected_components().unwrap(), vec![vec![1, 2, 3], vec![4]]);
        assert_eq!(graph.incidence_count(), 3);
    }

    #[test]
    fn empty_and_missing_member_hyperedges_are_rejected() {
        let mut graph = Hypergraph::new();
        graph.add_node(1, "one").unwrap();
        assert_eq!(graph.add_hyperedge(1, []), Err(HypergraphError::EmptyHyperedge));
        assert_eq!(graph.add_hyperedge(2, [1, 9]), Err(HypergraphError::MissingNode(9)));
    }

    #[test]
    fn fingerprint_is_deterministic() {
        let mut a = Hypergraph::new();
        let mut b = Hypergraph::new();
        for graph in [&mut a, &mut b] {
            graph.add_node(1, "a").unwrap();
            graph.add_node(2, "b").unwrap();
        }
        a.add_hyperedge(4, [1, 2]).unwrap();
        b.add_hyperedge(4, [2, 1]).unwrap();
        assert_eq!(a.fingerprint(), b.fingerprint());
    }
}
